void Board::draw(const std::deque<Pos>& snakeBody, const int current_len, const int max_len) const {
    clear();

    // 빈 맵 그리기
    for (int y = 0; y < MAP_SIZE; y++) {
        for (int x = 0; x < MAP_SIZE; x++) {
            if (stageData[y][x] == 1) mvprintw(y, x, "#");
            else if (stageData[y][x] == 2) mvprintw(y, x, "X");
            else mvprintw(y, x, " ");
        }
    }

    // 뱀 그리기
    for (size_t i = 0; i < snakeBody.size(); i++) {
        if (i == 0) mvprintw(snakeBody[i].y, snakeBody[i].x, "O"); // 머리
        else mvprintw(snakeBody[i].y, snakeBody[i].x, "o");        // 몸통
    }

    // 상태창 update
    mvprintw(MAP_SIZE + 1, 0, "Current Length: %d / Max Length: %d", current_len, max_len);

    refresh();
}

// 벽 충돌 판정
bool Board::checkWallCollision(const Pos p) const {
    if (stageData[p.y][p.x] == 1 || stageData[p.y][p.x] == 2) return true;
    return false;
}